// Package domain — сущности поиска.
//
// Ищется не «лента объявлений», а субъект: предмет, человек, животное,
// место или событие. Объявление (Publication) — это авторское высказывание
// о субъекте. У него три намерения:
//
//   - seeking — ищущий: «я потерял / я ищу»;
//   - found   — нашедший: «я нашёл / я видел»;
//   - marking — авторская отметка места, события или другого субъекта.
//     За такими авторами следят так же, как за каналом.
//
// Место и время потери или находки лежат на объявлении, а не на самом
// предмете: у одного субъекта может быть несколько сообщений
// («потерял у метро», «видели у парка»).
//
// Внешнее и внутреннее разделены явно. Публичная карточка (метод Public)
// не содержит владельца вещи, скрытую примету и автора объявления «ищу»,
// если автор не открыл себя сам. Паспорт и платёжные данные здесь не
// хранятся: у пользователя есть только статус подтверждения личности.
